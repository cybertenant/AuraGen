import { sql } from "drizzle-orm";
import {
  pgTable,
  pgEnum,
  uuid,
  timestamp,
  jsonb,
  integer,
  bigserial,
  text,
  uniqueIndex,
  index,
} from "drizzle-orm/pg-core";
import type { AggregatedSignals } from "@auragen/shared";

/**
 * PostgreSQL Enums for strict domain integrity
 */
export const frictionLevelEnum = pgEnum("friction_level", [
  "low",
  "medium",
  "high",
]);

export const uiAdaptationStatusEnum = pgEnum("ui_adaptation_status", [
  "generated",
  "validated",
  "rendered",
  "failed",
]);

/**
 * Table 1: sessions
 * Tracks anonymous user visits and interaction sessions.
 * Note: Anonymous session UUIDs are for synthetic demo isolation only and are NOT authentication.
 */
export const sessions = pgTable(
  "sessions",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    startedAt: timestamp("started_at", { withTimezone: true, mode: "date" })
      .defaultNow()
      .notNull(),
    lastSeenAt: timestamp("last_seen_at", { withTimezone: true, mode: "date" })
      .defaultNow()
      .notNull(),
    endedAt: timestamp("ended_at", { withTimezone: true, mode: "date" }),
  },
  (table) => ({
    lastSeenIdx: index("sessions_last_seen_at_idx").on(table.lastSeenAt),
  })
);

/**
 * Table 2: form_drafts
 * Persists the user's synthetic financial application draft (max 1 active draft per session).
 */
export const formDrafts = pgTable(
  "form_drafts",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    sessionId: uuid("session_id")
      .notNull()
      .references(() => sessions.id, { onDelete: "cascade" }),
    formData: jsonb("form_data")
      .$type<Record<string, unknown>>()
      .default(sql`'{}'::jsonb`)
      .notNull(),
    schemaVersion: integer("schema_version").default(1).notNull(),
    updatedAt: timestamp("updated_at", { withTimezone: true, mode: "date" })
      .defaultNow()
      .notNull(),
  },
  (table) => ({
    sessionUniqueIdx: uniqueIndex("form_drafts_session_id_unique").on(
      table.sessionId
    ),
  })
);

/**
 * Table 3: friction_events
 * Stores aggregated cognitive friction telemetry snapshots (0-100 score).
 */
export const frictionEvents = pgTable(
  "friction_events",
  {
    id: bigserial("id", { mode: "number" }).primaryKey(),
    sessionId: uuid("session_id")
      .notNull()
      .references(() => sessions.id, { onDelete: "cascade" }),
    frictionScore: integer("friction_score").notNull(),
    frictionLevel: frictionLevelEnum("friction_level").notNull(),
    signals: jsonb("signals").$type<AggregatedSignals>().notNull(),
    createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
      .defaultNow()
      .notNull(),
  },
  (table) => ({
    sessionCreatedIdx: index("friction_events_session_created_idx").on(
      table.sessionId,
      table.createdAt
    ),
  })
);

/**
 * Table 4: ui_adaptations
 * Stores structured JSON UI schemas generated by the AI agent (never executable JS).
 */
export const uiAdaptations = pgTable(
  "ui_adaptations",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    sessionId: uuid("session_id")
      .notNull()
      .references(() => sessions.id, { onDelete: "cascade" }),
    triggerScore: integer("trigger_score").notNull(),
    uiSchema: jsonb("ui_schema")
      .$type<Record<string, unknown>>()
      .notNull(),
    modelName: text("model_name"),
    generationTimeMs: integer("generation_time_ms"),
    status: uiAdaptationStatusEnum("status").default("generated").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
      .defaultNow()
      .notNull(),
  },
  (table) => ({
    sessionCreatedIdx: index("ui_adaptations_session_created_idx").on(
      table.sessionId,
      table.createdAt
    ),
  })
);

export type DbSession = typeof sessions.$inferSelect;
export type NewDbSession = typeof sessions.$inferInsert;

export type DbFormDraft = typeof formDrafts.$inferSelect;
export type NewDbFormDraft = typeof formDrafts.$inferInsert;

export type DbFrictionEvent = typeof frictionEvents.$inferSelect;
export type NewDbFrictionEvent = typeof frictionEvents.$inferInsert;

export type DbUiAdaptation = typeof uiAdaptations.$inferSelect;
export type NewDbUiAdaptation = typeof uiAdaptations.$inferInsert;